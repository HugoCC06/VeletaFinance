function syntheticCandles(seed: number, n: number, start: number): Candle[] {
  const r = rng(seed)
  const out: Candle[] = []
  let prev = start
  for (let i = 0; i < n; i++) {
    const trend = i < n * 0.45 ? 0.004 : i < n * 0.7 ? -0.006 : 0.005
    const o = round2(prev * (1 + (r() - 0.5) * 0.01))
    const c = round2(o * (1 + trend + gauss(r) * 0.018))
    const h = round2(Math.max(o, c) * (1 + r() * 0.012))
    const l = round2(Math.min(o, c) * (1 - r() * 0.012))
    out.push({ t: i + 1, o, h, l, c, v: Math.round(50_000 + r() * 150_000 * (1 + Math.abs(c - o) / o * 20)) })
    prev = c
  }
  return out
}

