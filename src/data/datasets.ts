/** mulberry32 PRNG — deterministic so charts never change between visits. */
export function rng(seed: number) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

/** Approximately normal random numbers (Box–Muller). */
function gauss(r: () => number) {
  const u = Math.max(r(), 1e-12)
  const v = r()
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v)
}

const round2 = (n: number) => Math.round(n * 100) / 100

function randomWalk(seed: number, steps: number, start: number, drift: number, vol: number, shocks: Record<number, number> = {}): [number, number][] {
  const r = rng(seed)
  const pts: [number, number][] = [[0, start]]
  let v = start
  for (let i = 1; i <= steps; i++) {
    v = v * Math.exp(drift - (vol * vol) / 2 + vol * gauss(r) + (shocks[i] ?? 0))
    pts.push([i, round2(v)])
  }
  return pts
}

