export function simpleMovingAverage(values: number[], period: number): (number | null)[] {
  if (period < 1) throw new Error('period must be >= 1')
  const out: (number | null)[] = []
  let sum = 0
  for (let i = 0; i < values.length; i++) {
    sum += values[i]
    if (i >= period) sum -= values[i - period]
    out.push(i >= period - 1 ? sum / period : null)
  }
  return out
}

/** Re-bases a series so its first point is 0% (percentage-change view). */
export function toPercentChange(points: [number, number][]): [number, number][] {
  if (!points.length || points[0][1] === 0) return points.map(([x]) => [x, 0])
  const base = points[0][1]
  return points.map(([x, y]) => [x, round2((y / base - 1) * 100)])
}

export function maxDrawdown(values: number[]): number {
  let peak = -Infinity
  let worst = 0
  for (const v of values) {
    peak = Math.max(peak, v)
    if (peak > 0) worst = Math.min(worst, v / peak - 1)
  }
  return worst
}

export function filterRange(points: [number, number][], from: number, to: number): [number, number][] {
  return points.filter(([x]) => x >= from && x <= to)
}
