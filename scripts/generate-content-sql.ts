/**
 * Generates supabase/migrations/20261016000004_content_seed.sql from the
 * TypeScript curriculum and game configuration, so the server grades answers
 * and awards XP from exactly the same source of truth as the app.
 *
 *   npm run content:sql     # write the file
 *   npm run content:check   # fail if the file is out of date (used in CI)
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { COURSES } from '../src/content/index.ts'
import { correctAnswer } from '../src/engine/grading.ts'
import { XP } from '../src/engine/rewards.ts'
import { DAILY_ROTATION, MISSION_TEMPLATES, WEEKLY_ROTATION } from '../src/engine/missions.ts'
import type { Question } from '../src/content/types.ts'

const OUT = fileURLToPath(new URL('../supabase/migrations/20261016000004_content_seed.sql', import.meta.url))

const lit = (s: string) => `'${s.replace(/'/g, "''")}'`
const num = (n: number) => (Number.isFinite(n) ? String(n) : 'null')
const json = (v: unknown) => `${lit(JSON.stringify(v))}::jsonb`
const arr = (xs: string[]) => `array[${xs.map(lit).join(', ')}]::text[]`

const lines: string[] = [
  '-- GENERATED by scripts/generate-content-sql.ts — do not edit by hand.',
  '-- Re-run `npm run content:sql` after changing src/content or game configuration.',
  '-- Rows are upserted, never deleted, so existing learner progress keeps valid references.',
  'begin;',
  '',
]

const upsert = (table: string, cols: string[], rows: string[][]) => {
  if (!rows.length) return
  lines.push(`insert into veleta_private.${table} (${cols.join(', ')}) values`)
  lines.push(rows.map((r) => `  (${r.join(', ')})`).join(',\n'))
  const updates = cols.filter((c) => c !== cols[0]).map((c) => `${c} = excluded.${c}`)
  lines.push(`on conflict (${cols[0]}) do update set ${updates.join(', ')};`, '')
}

upsert('config', ['key', 'value'], Object.entries(XP).map(([k, v]) => [lit(k), num(v)]))
upsert('mission_templates', ['id', 'period', 'metric', 'target', 'title'], MISSION_TEMPLATES.map((t) => [lit(t.id), lit(t.period), lit(t.metric), num(t.target), lit(t.title)]))
lines.push('delete from veleta_private.mission_rotation;')
lines.push('insert into veleta_private.mission_rotation (period, idx, template_ids) values')
lines.push(
  [...DAILY_ROTATION.map((ids, i) => `  ('daily', ${i}, ${arr(ids)})`), ...WEEKLY_ROTATION.map((ids, i) => `  ('weekly', ${i}, ${arr(ids)})`)].join(',\n') + ';',
  '',
)

upsert('courses', ['id', 'title', 'pass_mark', 'position'], COURSES.map((c, i) => [lit(c.id), lit(c.title), num(c.passMark), num(i + 1)]))
upsert('units', ['id', 'course_id', 'position', 'title'], COURSES.flatMap((c) => c.units.map((u, i) => [lit(u.id), lit(c.id), num(i + 1), lit(u.title)])))
upsert(
  'lessons',
  ['id', 'course_id', 'unit_id', 'position', 'title'],
  COURSES.flatMap((c) => c.units.flatMap((u) => u.lessons.map((l, i) => [lit(l.id), lit(c.id), lit(u.id), num(i + 1), lit(l.title)]))),
)
upsert(
  'assessments',
  ['id', 'kind', 'course_id', 'unit_id', 'pass_mark', 'title'],
  COURSES.flatMap((c) => [
    ...c.units.map((u) => [lit(u.checkpoint.id), lit('checkpoint'), lit(c.id), lit(u.id), num(u.checkpoint.passMark), lit(u.checkpoint.title)]),
    [lit(c.exam.id), lit('exam'), lit(c.id), 'null', num(c.exam.passMark), lit(c.exam.title)],
  ]),
)

const qRow = (q: Question, lessonId: string | null, assessmentId: string | null) => [
  lit(q.id),
  lit(q.kind),
  lessonId ? lit(lessonId) : 'null',
  assessmentId ? lit(assessmentId) : 'null',
  json(correctAnswer(q)),
  num(q.kind === 'numeric' ? q.tolerance : 0),
  lit(q.concept),
]
const qRows: string[][] = []
for (const c of COURSES) {
  for (const u of c.units) {
    for (const l of u.lessons) for (const s of l.steps) if (s.kind === 'question') qRows.push(qRow(s.question, l.id, null))
    for (const q of u.checkpoint.questions) qRows.push(qRow(q, null, u.checkpoint.id))
  }
  for (const q of c.exam.questions) qRows.push(qRow(q, null, c.exam.id))
}
upsert('questions', ['id', 'kind', 'lesson_id', 'assessment_id', 'answer', 'tolerance', 'concept'], qRows)
lines.push('commit;', '')

const sql = lines.join('\n')

/** supabase/setup.sql = every migration in order, for one-paste setup in the Supabase SQL editor. */
const MIGRATIONS = fileURLToPath(new URL('../supabase/migrations/', import.meta.url))
const SETUP = fileURLToPath(new URL('../supabase/setup.sql', import.meta.url))
function bundle(seed: string) {
  const parts = ['-- Veleta Finance: complete database setup (all migrations in order).', '-- Paste this whole file into Supabase → SQL Editor → New query, then press Run. Run it ONCE.', '']
  for (const f of readdirSync(MIGRATIONS).filter((x) => x.endsWith('.sql')).sort()) {
    parts.push('', `-- ===== ${f} =====`, f.endsWith('_content_seed.sql') ? seed : readFileSync(MIGRATIONS + f, 'utf8'))
  }
  return parts.join('\n')
}

if (process.argv.includes('--check')) {
  let setup = ''
  try { setup = readFileSync(SETUP, 'utf8') } catch { /* missing */ }
  if (setup !== bundle(sql)) {
    console.error('supabase/setup.sql is out of date. Run `npm run content:sql` and commit the result.')
    process.exit(1)
  }
  let current = ''
  try {
    current = readFileSync(OUT, 'utf8')
  } catch {
    /* missing */
  }
  if (current !== sql) {
    console.error('Content seed SQL is out of date. Run `npm run content:sql` and commit the result.')
    process.exit(1)
  }
  console.log(`Content seed is up to date (${qRows.length} questions).`)
} else {
  writeFileSync(OUT, sql)
  writeFileSync(SETUP, bundle(sql))
  console.log(`Wrote ${OUT} (${qRows.length} questions).`)
}
